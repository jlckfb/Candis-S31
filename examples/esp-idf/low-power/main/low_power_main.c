/**
 * Bring up the CO5300 panel and the CST820 controller.
 *
 * bsp_display_new() is used instead of bsp_display_start(): the prototype has
 * no UI, and this keeps LVGL out of the runtime path while still giving
 * bsp_display_enter_sleep()/exit_sleep() the panel handle they require.
 */
static esp_err_t display_and_touch_start(void)
{
    if (s_display_ready) {
        return ESP_OK;
    }
    const bsp_display_config_t config = {
        .max_transfer_sz = BSP_LCD_H_RES * 80 * (int)sizeof(uint16_t),
    };
    ESP_RETURN_ON_ERROR(bsp_display_new(&config, &s_panel, &s_panel_io), TAG,
                        "CO5300 bring-up failed");
    s_display_ready = true;
    s_display_asleep = false;

    /* Touch is optional during EVT: a loose FPC must not stop the state
     * machine, it only removes the touch wake source. */
    if (bsp_touch_new(NULL, &s_touch) != ESP_OK) {
        s_touch = NULL;
        ESP_LOGW(TAG, "CST820 bring-up failed, continuing without touch wake");
    }
    return ESP_OK;
}

/**
 * Put panel and touch into their S1 low-power modes.
 *
 * bsp_display_enter_sleep() also drives the touch controller into its deep
 * sleep (~2 uA) through esp_lcd_touch_enter_sleep(), and that mode cannot be
 * woken by a touch. Monitor mode is therefore restored afterwards with a reset
 * cycle: esp_lcd_touch_cst820_wakeup() brings the controller back to dynamic
 * mode, and enter_monitor_mode() lets it fall into touch-wakeable standby.
 */
static esp_err_t display_and_touch_sleep(void)
{
    ESP_RETURN_ON_FALSE(s_display_ready, ESP_ERR_INVALID_STATE, TAG,
                        "display is not initialized");
    ESP_RETURN_ON_ERROR(bsp_display_enter_sleep(), TAG,
                        "CO5300 sleep-in failed");
    s_display_asleep = true;

    if (s_touch != NULL) {
        const esp_err_t wake_error = esp_lcd_touch_cst820_wakeup(s_touch);
        if (wake_error != ESP_OK) {
            ESP_LOGW(TAG, "CST820 reset out of deep sleep failed: %s",
                     esp_err_to_name(wake_error));
        }
        const esp_err_t monitor_error =
            esp_lcd_touch_cst820_enter_monitor_mode(s_touch);
        if (monitor_error != ESP_OK) {
            ESP_LOGW(TAG, "CST820 monitor mode failed: %s",
                     esp_err_to_name(monitor_error));
        }
    }
    return ESP_OK;
}

/** Restore panel and touch after S1. */
static esp_err_t display_and_touch_resume(void)
{
    ESP_RETURN_ON_FALSE(s_display_ready, ESP_ERR_INVALID_STATE, TAG,
                        "display is not initialized");
    if (s_touch != NULL) {
        /* Reset path back to dynamic mode; the controller would also leave
         * standby on its own at the next touch. */
        const esp_err_t error = esp_lcd_touch_cst820_exit_monitor_mode(s_touch);
        if (error != ESP_OK) {
            ESP_LOGW(TAG, "CST820 monitor exit failed: %s",
                     esp_err_to_name(error));
        }
    }
    if (s_display_asleep) {
        ESP_RETURN_ON_ERROR(bsp_display_exit_sleep(), TAG,
                            "CO5300 sleep-out failed");
        s_display_asleep = false;
    }
    return ESP_OK;
}

/* ---------------------------------------------------------------------------
 * RTC alarm for S2
 * ------------------------------------------------------------------------- */

static uint8_t days_in_month(uint16_t year, uint8_t month)
{
    static const uint8_t lengths[12] = {
        31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31
    };
    if (month < 1 || month > 12) {
        return 31;
    }
    if (month == 2 &&
            ((year % 4 == 0 && year % 100 != 0) || year % 400 == 0)) {
        return 29;
    }
    return lengths[month - 1];
}

/** Advance a calendar value by whole minutes, carrying into the month. */
static void time_add_minutes(rx8130ce_time_t *time, uint16_t minutes)
{
    uint32_t total = (uint32_t)time->minute + minutes;
    time->minute = (uint8_t)(total % 60U);
    uint32_t hours = (uint32_t)time->hour + total / 60U;
    time->hour = (uint8_t)(hours % 24U);
    uint32_t days = hours / 24U;
    while (days-- > 0) {
        const uint8_t length = days_in_month(time->year, time->month);
        if (time->day < length) {
            time->day++;
        } else {
            time->day = 1;
            if (time->month == 12) {
                time->month = 1;
                time->year++;
            } else {
                time->month++;
            }
        }
        time->weekday = (uint8_t)((time->weekday + 1U) % 7U);
    }
}

/**
 * Arm the RX8130CE alarm S2_ALARM_MINUTES from now.
 *
 * The board carries no 32.768 kHz crystal, so the RTC alarm is the only
 * hardware timed path that survives the main rail going down. Sequence
 * follows the shared-IRQ contract: set the alarm, gate it onto /IRQ, clear
 * any latched flag, then confirm the shared line is released before sleeping.
 */
static esp_err_t arm_rtc_wakeup_alarm(void)
{
    bsp_rtc_time_t bsp_now = {0};
    bsp_rtc_status_t status = {0};
    ESP_RETURN_ON_ERROR(bsp_rtc_get_time(&bsp_now, &status), TAG,
                        "RTC time read failed");
    if (!status.time_valid) {
        /* VLF=1: the backup domain dropped out, so the calendar and the alarm
         * registers are meaningless. Refusing to continue is safer than
         * cutting the main rail with an alarm that will never fire. */
        ESP_LOGE(TAG, "RTC reports invalid time (VLF set); refusing to arm");
        return ESP_ERR_INVALID_STATE;
    }

    /* bsp_rtc_time_t and rx8130ce_time_t are distinct but field-identical;
     * rx8130ce_alarm_from_time() is a pure helper on the driver type. */
    const rx8130ce_time_t now = {
        .year = bsp_now.year,
        .month = bsp_now.month,
        .day = bsp_now.day,
        .weekday = bsp_now.weekday,
        .hour = bsp_now.hour,
        .minute = bsp_now.minute,
        .second = bsp_now.second,
    };
    rx8130ce_time_t target = now;
    time_add_minutes(&target, S2_ALARM_MINUTES);

    bsp_rtc_alarm_t alarm = {0};
    ESP_RETURN_ON_ERROR(rx8130ce_alarm_from_time(&now, &target, &alarm), TAG,
                        "alarm conversion failed");
    ESP_RETURN_ON_ERROR(bsp_rtc_set_alarm(&alarm), TAG, "alarm write failed");
    ESP_RETURN_ON_ERROR(bsp_rtc_alarm_irq_enable(true), TAG,
                        "alarm IRQ enable failed");

    /* Clear only AF before draining the wire-ANDed line. UF/TF remain
     * available to their consumers unless they are themselves holding the
     * shared line low, in which case service_shared_irq() reports and clears
     * them while making the shutdown wake path safe. */
    ESP_RETURN_ON_ERROR(bsp_rtc_get_and_clear_alarm_flag(NULL), TAG,
                        "alarm flag clear failed");
    bsp_shared_irq_status_t irq_status = {0};
    ESP_RETURN_ON_ERROR(service_shared_irq(&irq_status), TAG,
                        "shared IRQ line drain before shutdown failed");
    ESP_RETURN_ON_FALSE(irq_status.line_released, ESP_ERR_TIMEOUT, TAG,
                        "shared IRQ line remained asserted before shutdown");

    ESP_LOGI(TAG, "RTC alarm armed for %04u-%02u-%02u %02u:%02u "
             "(now %02u:%02u:%02u, +%d min)",
             (unsigned)target.year, (unsigned)target.month,
             (unsigned)target.day, (unsigned)target.hour,
             (unsigned)target.minute, (unsigned)now.hour,
             (unsigned)now.minute, (unsigned)now.second,
             S2_ALARM_MINUTES);
    return ESP_OK;
}

