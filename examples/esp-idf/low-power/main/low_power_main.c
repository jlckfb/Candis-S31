/** Log which sources woke the HP core from the last light sleep. */
static void log_wakeup_causes(void)
{
    const uint32_t causes = esp_sleep_get_wakeup_causes();
    ESP_LOGI(TAG, "wake causes 0x%08x%s%s%s%s", (unsigned)causes,
             (causes & BIT(ESP_SLEEP_WAKEUP_TIMER)) ? " timer" : "",
             (causes & BIT(ESP_SLEEP_WAKEUP_GPIO)) ? " gpio" : "",
             (causes & BIT(ESP_SLEEP_WAKEUP_ULP)) ? " ulp" : "",
             (causes & BIT(ESP_SLEEP_WAKEUP_UNDEFINED)) ? " undefined" : "");
}

/**
 * Arm light-sleep wake sources for S1.
 *
 * gpio_wakeup_enable() plus esp_sleep_enable_gpio_wakeup() is the light-sleep
 * path that works on any pad. The shared line and the optional touch line are
 * active low and externally pulled up, so present sources use level low.
 */
static esp_err_t arm_light_sleep_sources(bool include_shared_irq)
{
    if (s_touch != NULL) {
        ESP_RETURN_ON_ERROR(gpio_wakeup_enable(BSP_TOUCH_INT,
                            GPIO_INTR_LOW_LEVEL), TAG,
                            "touch INT wake-up arm failed");
    }
    if (include_shared_irq) {
        /* Only valid while the LP core is stopped: otherwise the pad belongs
         * to the LP core and this HP-side configuration fights it.
         * The pad is (re)configured as a digital input here because
         * stop_lp_housekeeper() released the RTC function and nothing else
         * guarantees a digital input configuration at this point. */
        const gpio_config_t shared_irq_input = {
            .pin_bit_mask = BIT64(BSP_PMIC_RTC_INT),
            .mode = GPIO_MODE_INPUT,
            .pull_up_en = GPIO_PULLUP_ENABLE,
            .pull_down_en = GPIO_PULLDOWN_DISABLE,
            .intr_type = GPIO_INTR_DISABLE,
        };
        ESP_RETURN_ON_ERROR(gpio_config(&shared_irq_input), TAG,
                            "shared IRQ input config failed");
        ESP_RETURN_ON_ERROR(gpio_wakeup_enable(BSP_PMIC_RTC_INT,
                                               GPIO_INTR_LOW_LEVEL),
                            TAG, "shared IRQ wake-up arm failed");
    }
    ESP_RETURN_ON_ERROR(esp_sleep_enable_gpio_wakeup(), TAG,
                        "GPIO wake-up source enable failed");
    return ESP_OK;
}

/** Release the wake sources armed by arm_light_sleep_sources(). */
static void disarm_light_sleep_sources(bool include_shared_irq)
{
    if (s_touch != NULL) {
        (void)gpio_wakeup_disable(BSP_TOUCH_INT);
    }
    if (include_shared_irq) {
        (void)gpio_wakeup_disable(BSP_PMIC_RTC_INT);
    }
    (void)esp_sleep_disable_wakeup_source(ESP_SLEEP_WAKEUP_GPIO);
}

