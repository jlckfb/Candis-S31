/**
 * Report why this boot happened.
 *
 * After S2 the ESP was unpowered, so a return from S2 is a cold boot and the
 * wake cause reads as undefined. The PMIC power-on source and the RTC alarm
 * flag are what actually identify an alarm-driven restart, which is why the
 * shared line is drained here before anything else touches it.
 */
static esp_err_t report_boot_reason(void)
{
    log_wakeup_causes();

    uint8_t power_on_source = 0;
    if (bsp_pmic_get_power_on_source(&power_on_source) == ESP_OK) {
        ESP_LOGI(TAG, "PMIC power-on source 0x%02x", power_on_source);
    }

    bsp_rtc_status_t rtc_status = {0};
    if (bsp_rtc_get_status(&rtc_status) == ESP_OK) {
        ESP_LOGI(TAG, "RTC flags 0x%02x: time_valid=%d alarm=%d timer=%d "
                 "backup_low=%d", rtc_status.raw, (int)rtc_status.time_valid,
                 (int)rtc_status.alarm, (int)rtc_status.timer,
                 (int)rtc_status.backup_voltage_low);
    }

    /* Contract D3: drain the shared line once at start-up whatever the wake
     * reason was, so a latched AF cannot hold GPIO2 low into the application. */
    bsp_shared_irq_status_t irq_status = {0};
    const esp_err_t error = service_shared_irq(&irq_status);
    ESP_LOGI(TAG, "start-up shared IRQ drain: %s, pmic %02x %02x %02x, "
             "rtc %02x, passes %u, released %d", esp_err_to_name(error),
             irq_status.pmic[0], irq_status.pmic[1], irq_status.pmic[2],
             irq_status.rtc, irq_status.service_passes,
             (int)irq_status.line_released);
    return error;
}

static esp_err_t board_bring_up(void)
{
    ESP_RETURN_ON_ERROR(bsp_board_init(), TAG, "board init failed");
    ESP_RETURN_ON_ERROR(bsp_lp_i2c_init(), TAG, "low-power I2C init failed");
    ESP_RETURN_ON_ERROR(bsp_pmic_init(), TAG, "TG28 init failed");
    ESP_RETURN_ON_ERROR(bsp_rtc_init(), TAG, "RX8130CE init failed");

    /* The shared IRQ pad is claimed and released around the LP core lifetime
     * (see start_lp_housekeeper() / stop_lp_housekeeper()) rather than being
     * configured once here, so only the capability is checked at bring-up. */
    if (!rtc_gpio_is_valid_gpio(BSP_PMIC_RTC_INT)) {
        ESP_LOGW(TAG, "GPIO%d is not an RTC pad; the LP housekeeper cannot "
                 "watch the shared IRQ line", BSP_PMIC_RTC_INT);
    }
    return ESP_OK;
}

void app_main(void)
{
    ESP_LOGI(TAG, "%s low-power prototype, board %s",
             BSP_BOARD_NAME, BSP_BOARD_REVISION);

    s_lp_reports = xQueueCreate(LP_REPORT_QUEUE_DEPTH, sizeof(int32_t));
    if (s_lp_reports == NULL) {
        ESP_LOGE(TAG, "LP report queue allocation failed");
        return;
    }

    if (board_bring_up() != ESP_OK) {
        ESP_LOGE(TAG, "board bring-up failed; re-applying safe state");
        (void)low_power_safe_state();
        return;
    }
    if (report_boot_reason() != ESP_OK) {
        ESP_LOGE(TAG, "start-up shared IRQ could not be drained; stopping");
        (void)low_power_safe_state();
        return;
    }

    /* Route the boot. Waking from deep sleep reboots the chip with a real
     * wake cause (timer, EXT1, ...); every other boot - power-on, reset, or
     * the cold start after S2 cut the power - reports UNDEFINED and starts a
     * fresh cycle with the counter zeroed. For a deep-sleep wake the counter
     * in RTC memory decides between another S0 pass and the escalation to S2.
     * This does not disturb report_boot_reason(): an S2 restart still shows
     * up as UNDEFINED there, because the ESP was unpowered, not deep-sleeping. */
    /* Route the boot. Waking from deep sleep reboots the chip with a real
     * wake cause (timer, EXT1, ...); every other boot - power-on, reset, or
     * the cold start after S2 cut the power - reports UNDEFINED and starts a
     * fresh cycle with the counter zeroed.
     *
     * Within a deep-sleep wake, the source matters:
     * - EXT1 on GPIO2 means an external event (power key, RTC alarm) — the
     *   user or an alarm explicitly wants the board, so reset the counter
     *   and return to S0 regardless of how many idle cycles elapsed.
     * - TIMER means idle timeout — honour the escalation budget: another S0
     *   pass if the counter is within budget, S2 otherwise.
     * Both sources can fire simultaneously; EXT1 takes precedence so a
     * coincident timer expiry never sends a user wake to S2. */
    candis_state_t state;
    const uint32_t wake_causes = esp_sleep_get_wakeup_causes();
    if (wake_causes & BIT(ESP_SLEEP_WAKEUP_UNDEFINED)) {
        deep_sleep_counter_reset();
        state = CANDIS_STATE_RUN;
    } else if (wake_causes & BIT(ESP_SLEEP_WAKEUP_EXT1)) {
        ESP_LOGI(TAG, "woke from deep sleep by EXT1 (external event: "
                 "power key or RTC alarm), resetting counter and returning to S0");
        deep_sleep_counter_reset();
        state = CANDIS_STATE_RUN;
    } else if (deep_sleep_cycles_done() >= DEEP_SLEEP_MAX_CYCLES) {
        ESP_LOGI(TAG, "deep-sleep budget exhausted (%u cycles), going to S2",
                 (unsigned)deep_sleep_cycles_done());
        state = CANDIS_STATE_SHUTDOWN;
    } else {
        ESP_LOGI(TAG, "woke from deep sleep by timer, cycle %u/%u, returning to S0",
                 (unsigned)deep_sleep_cycles_done(),
                 (unsigned)DEEP_SLEEP_MAX_CYCLES);
        state = CANDIS_STATE_RUN;
    }

    while (1) {
        ESP_LOGI(TAG, "==> entering %s", state_name(state));
        switch (state) {
        case CANDIS_STATE_RUN:
            if (enter_run() != ESP_OK) {
                ESP_LOGE(TAG, "S0 entry failed");
                vTaskDelay(pdMS_TO_TICKS(2000));
                break;
            }
            run_state_run();
            state = CANDIS_STATE_SCREEN_OFF;
            break;

        case CANDIS_STATE_SCREEN_OFF:
            if (enter_screen_off() != ESP_OK) {
                ESP_LOGE(TAG, "S1 entry failed, returning to S0");
                exit_screen_off();
                state = CANDIS_STATE_RUN;
                break;
            }
            {
                const bool user_wake = run_state_screen_off();
                exit_screen_off();
                /* A touch returns to S0; exhausting the budget drops the
                 * machine into deep sleep first. */
                state = user_wake ? CANDIS_STATE_RUN : CANDIS_STATE_DEEP_SLEEP;
            }
            break;

        case CANDIS_STATE_DEEP_SLEEP:
            if (enter_deep_sleep() != ESP_OK) {
                /* No wake source could be armed: deep sleep would be
                 * permanent. Escalate to S2 instead. */
                ESP_LOGE(TAG, "deep-sleep entry failed, escalating to S2");
                state = CANDIS_STATE_SHUTDOWN;
                break;
            }
            /* Not reached: waking from deep sleep reboots the chip. */
            state = CANDIS_STATE_RUN;
            break;

        case CANDIS_STATE_SHUTDOWN:
            if (enter_shutdown() != ESP_OK) {
                ESP_LOGE(TAG, "S2 entry failed");
            }
            /* Reached only when the PMIC power-off was refused. Idle instead
             * of looping back: the peripheral rails are down and re-running
             * S0 would need a full re-initialization. */
            ESP_LOGW(TAG, "still powered after S2; idling. Reset the board or "
                     "cycle power to restart the state machine.");
            while (1) {
                vTaskDelay(pdMS_TO_TICKS(10000));
            }
            break;

        default:
            state = CANDIS_STATE_RUN;
            break;
        }
    }
}
