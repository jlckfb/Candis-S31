/** Enter S0: panel on, LP housekeeper delegated the shared-IRQ watch. */
static esp_err_t enter_run(void)
{
    ESP_RETURN_ON_ERROR(display_and_touch_start(), TAG,
                        "display bring-up failed");
    ESP_RETURN_ON_ERROR(display_and_touch_resume(), TAG,
                        "display resume failed");
    ESP_RETURN_ON_ERROR(start_lp_housekeeper(), TAG,
                        "LP housekeeper start failed");

    /* The LP core owns GPIO2, so the HP core does not arm it. It still needs
     * a wake path for the mailbox notification: that is the ULP source. */
    ESP_RETURN_ON_ERROR(esp_sleep_enable_ulp_wakeup(), TAG,
                        "ULP wake-up enable failed");
    return ESP_OK;
}

/**
 * Run S0 for its dwell time.
 *
 * This is the delegation demo: instead of polling the RTC and PMIC itself, the
 * HP core light-sleeps in slices and only wakes when the LP core reports, or
 * when the slice timer expires.
 */
static void run_state_run(void)
{
    const int slices = (S0_DWELL_SECONDS * 1000000) / (int)S0_SLEEP_SLICE_US;
    for (int slice = 0; slice < slices; ++slice) {
        if (esp_sleep_enable_timer_wakeup(S0_SLEEP_SLICE_US) != ESP_OK) {
            ESP_LOGE(TAG, "timer wake-up arm failed, staying awake");
            vTaskDelay(pdMS_TO_TICKS(S0_SLEEP_SLICE_US / 1000));
        } else if (esp_light_sleep_start() != ESP_OK) {
            ESP_LOGW(TAG, "light sleep rejected in S0");
            vTaskDelay(pdMS_TO_TICKS(100));
        } else {
            log_wakeup_causes();
        }
        drain_lp_reports();
    }
    (void)esp_sleep_disable_wakeup_source(ESP_SLEEP_WAKEUP_TIMER);
}

/**
 * Enter S1: panel and touch to low power, LP core stopped, HP light-sleeping.
 *
 * The LP core is stopped so the HP core can own GPIO2 and take the shared IRQ
 * line directly as a level-low wake source, which is what the state
 * definition calls for. Keeping the LP core running instead would mean waking
 * through the ULP source; the two cannot both drive the pad.
 */
static esp_err_t enter_screen_off(void)
{
    ESP_RETURN_ON_ERROR(display_and_touch_sleep(), TAG,
                        "display sleep failed");
    stop_lp_housekeeper();
    (void)esp_sleep_disable_wakeup_source(ESP_SLEEP_WAKEUP_ULP);
    ESP_RETURN_ON_ERROR(arm_light_sleep_sources(true), TAG,
                        "S1 wake-up sources failed");
    return ESP_OK;
}

/**
 * Light-sleep in S1 until a wake source fires or the escalation budget ends.
 *
 * @return true when the user asked to come back (touch), false when the budget
 *         ran out and the machine should drop into deep sleep. The result is
 *         returned explicitly instead of re-reading esp_sleep_get_wakeup_causes()
 *         afterwards: a shared-IRQ wake also sets the GPIO cause bit, so the
 *         cause bitmap alone cannot tell "user touched" from "PMIC/RTC event".
 */
static bool run_state_screen_off(void)
{
    bool user_requested_wake = false;
    for (int slice = 0; slice < S1_SLICES_BEFORE_S2; ++slice) {
        if (esp_sleep_enable_timer_wakeup(S1_SLEEP_SLICE_US) != ESP_OK) {
            ESP_LOGE(TAG, "timer wake-up arm failed in S1");
            break;
        }
        if (esp_light_sleep_start() != ESP_OK) {
            ESP_LOGW(TAG, "light sleep rejected in S1");
            vTaskDelay(pdMS_TO_TICKS(100));
            continue;
        }
        const uint32_t causes = esp_sleep_get_wakeup_causes();
        log_wakeup_causes();

        if (causes & BIT(ESP_SLEEP_WAKEUP_GPIO)) {
            /* Either the panel was touched or one of the I2C devices behind
             * the shared line asserted. Reading the levels tells them apart:
             * both lines are active low. */
            const bool shared_low =
                gpio_get_level(BSP_PMIC_RTC_INT) == BSP_PMIC_RTC_INT_ACTIVE_LEVEL;
            const bool touch_low = s_touch != NULL &&
                                   gpio_get_level(BSP_TOUCH_INT) == 0;
            ESP_LOGI(TAG, "S1 GPIO wake: shared_irq=%d touch=%d",
                     (int)shared_low, (int)touch_low);
            if (shared_low) {
                /* The LP core is stopped in S1, so service_shared_irq() only
                 * forwards to the BSP here; it is used for consistency. */
                bsp_shared_irq_status_t status = {0};
                const esp_err_t error = service_shared_irq(&status);
                ESP_LOGI(TAG, "shared IRQ service: %s, pmic %02x %02x %02x, "
                         "rtc %02x, released %d",
                         esp_err_to_name(error),
                         status.pmic[0], status.pmic[1], status.pmic[2],
                         status.rtc, (int)status.line_released);
                /* TG28 power-key IRQs live in bank 1 bits 0-3
                 * (PONPE/PONNE/PONLP/PONSP, see tg28_sw.h). Treat a
                 * short or long press as a user request to wake — the
                 * power key is the natural wake gesture while the screen
                 * is off. */
                if (error == ESP_OK && (status.pmic[1] & 0x0F) != 0) {
                    ESP_LOGI(TAG, "power key detected on shared IRQ, waking to S0");
                    user_requested_wake = true;
                    break;
                }
            }
            if (touch_low) {
                /* A touch is a user request to come back: leave S1. */
                user_requested_wake = true;
                break;
            }
        }
    }
    (void)esp_sleep_disable_wakeup_source(ESP_SLEEP_WAKEUP_TIMER);
    return user_requested_wake;
}

/** Leave S1 and release the wake sources it owns. */
static void exit_screen_off(void)
{
    disarm_light_sleep_sources(true);
}

/** Release protocol owners while their supplies are still present.
 *
 * Boot failure, deep sleep, and S2 all use this idempotent helper before the
 * BSP parks pins or removes rails.
 */
static esp_err_t stop_active_peripheral_owners(void)
{
    esp_err_t first_error = ESP_OK;
    if (s_touch != NULL) {
        first_error = bsp_touch_delete();
    }
    if (s_display_ready) {
        bsp_display_delete();
    }
    s_display_ready = false;
    s_display_asleep = false;
    s_touch = NULL;
    s_panel = NULL;
    s_panel_io = NULL;
    return first_error;
}

static esp_err_t low_power_safe_state(void)
{
    const esp_err_t owner_error = stop_active_peripheral_owners();
    const esp_err_t rail_error = bsp_power_safe_state();
    return owner_error != ESP_OK ? owner_error : rail_error;
}

/**
 * Enter deep sleep, the step between S1 and S2.
 *
 * The panel/touch protocol owners and every optional rail are shut down before
 * entry. On wake the ESP reboots and bsp_board_init() applies the same safe
 * state again, so S0 reinitializes peripherals rather than relying on their
 * state to survive. The always-on RX8130CE/TG28 behind the shared IRQ line do
 * not depend on an optional peripheral rail.
 *
 * Wake sources are the SoC RTC timer and EXT1 (any low) on the shared IRQ
 * line. Only PMIC/RTC events can assert that line: the CST820 touch INT is
 * GPIO3 and is NOT wired to GPIO2, so a touch cannot wake deep sleep in
 * this configuration. Waking from deep sleep reboots the chip, so this
 * function does not return on success; app_main reads the cycle counter
 * from RTC memory on the next boot and routes the machine back to S0 or on
 * to S2.
 */
static esp_err_t enter_deep_sleep(void)
{
    /* Idempotent: S1 already stopped the housekeeper, but this guarantees
     * GPIO2 is back on the HP side however the machine got here. */
    stop_lp_housekeeper();

    /* The S1 light-sleep sources use the digital pad function; EXT1 needs the
     * RTC function instead, so they must go before the pad is re-muxed. */
    disarm_light_sleep_sources(true);

    /* Deep sleep must not preserve optional rails. Release active protocol
     * owners, then park pins and remove every peripheral/control supply. */
    const esp_err_t safe_error = low_power_safe_state();
    if (safe_error != ESP_OK) {
        ESP_LOGE(TAG, "pre-deep-sleep safe-state failed: %s",
                 esp_err_to_name(safe_error));
        return safe_error;
    }

    const esp_err_t timer_error =
        esp_sleep_enable_timer_wakeup(DEEP_SLEEP_WAKE_US);
    if (timer_error != ESP_OK) {
        ESP_LOGE(TAG, "deep-sleep timer wake-up arm failed: %s",
                 esp_err_to_name(timer_error));
    }

    /* EXT1 on the shared IRQ line. GPIO2 is pulled up through R10; enable the
     * internal pull-up as well so the pad keeps a defined level even without
     * the external resistor. A floating EXT1 pin is exactly what keeps the
     * chip in deep sleep forever. Only TG28/RX8130CE events assert this line;
     * touch (GPIO3) is deliberately not armed - see the function comment. */
    esp_err_t ext1_error = rtc_gpio_init(BSP_PMIC_RTC_INT);
    if (ext1_error == ESP_OK) {
        ext1_error = rtc_gpio_set_direction(BSP_PMIC_RTC_INT,
                                            RTC_GPIO_MODE_INPUT_ONLY);
    }
    if (ext1_error == ESP_OK) {
        ext1_error = rtc_gpio_pullup_en(BSP_PMIC_RTC_INT);
    }
    if (ext1_error == ESP_OK) {
        ext1_error = esp_sleep_enable_ext1_wakeup_io(BIT(BSP_PMIC_RTC_INT),
                                                     ESP_EXT1_WAKEUP_ANY_LOW);
    }
    if (ext1_error != ESP_OK) {
        ESP_LOGE(TAG, "deep-sleep EXT1 wake-up arm failed: %s",
                 esp_err_to_name(ext1_error));
    }

    if (timer_error != ESP_OK && ext1_error != ESP_OK) {
        /* With no wake source armed, deep sleep would be permanent. Refuse it
         * so the state machine escalates to S2 instead. */
        return ESP_ERR_INVALID_STATE;
    }

    s_deep_sleep_counter.magic = DEEP_SLEEP_COUNT_MAGIC;
    s_deep_sleep_counter.cycles++;

    ESP_LOGW(TAG, "deep sleep: cycle %u/%u, wake on RTC timer (%u s) or "
             "GPIO%d low (EXT1)",
             (unsigned)s_deep_sleep_counter.cycles,
             (unsigned)DEEP_SLEEP_MAX_CYCLES,
             (unsigned)(DEEP_SLEEP_WAKE_US / 1000000ULL),
             BSP_PMIC_RTC_INT);
    vTaskDelay(pdMS_TO_TICKS(50));   /* let the log drain */
    esp_deep_sleep_start();

    /* Not reached: waking from deep sleep reboots the chip. */
    return ESP_OK;
}

/**
 * Enter S2: shed the peripheral rails, arm the RTC alarm, then ask the PMIC
 * for a software power-off so the board loses power.
 *
 * Order matters. Peripherals go first so nothing is back-fed while its supply
 * collapses, the alarm is armed while I2C is still alive, and DCDC1 is last
 * because the ESP dies with it.
 */
static esp_err_t enter_shutdown(void)
{
    stop_lp_housekeeper();
    disarm_light_sleep_sources(true);

    const esp_err_t safe_error = low_power_safe_state();
    if (safe_error != ESP_OK) {
        ESP_LOGE(TAG, "board safe-state failed: %s",
                 esp_err_to_name(safe_error));
        /* Do not cut the main rail after incomplete owner/rail teardown:
         * remain powered with the failure visible for diagnosis. */
        return safe_error;
    }

    /* VBUS guard: when USB power is present the TG28 REG10 bit0 soft-power-off
     * may reboot the board instead of cutting power (bring-up.md documents this
     * against the Linux reference implementation). Without this guard the
     * machine would loop: S2 → reboot → cold boot (counter reset) → S0 → S1 →
     * deep sleep → S2 → reboot … never actually turning off. Refuse the
     * power-off so the caller can idle with the rails safely down. The alarm
     * is still armed so the board wakes on schedule once USB is removed. */
    bsp_pmic_status_t pmic_status = {0};
    if (bsp_pmic_get_status(&pmic_status) == ESP_OK && pmic_status.vbus_present) {
        ESP_LOGW(TAG, "VBUS present: deferring PMIC power-off to avoid reboot "
                 "loop; the board stays powered with all peripheral rails off. "
                 "Remove USB to complete shutdown or reset to restart.");
        return ESP_ERR_INVALID_STATE;
    }

    ESP_RETURN_ON_ERROR(arm_rtc_wakeup_alarm(), TAG,
                        "RTC wake-up alarm failed");

    ESP_LOGW(TAG, "requesting PMIC power-off: the board loses power now");
    vTaskDelay(pdMS_TO_TICKS(50));   /* let the log drain */
    const esp_err_t power_off = bsp_pmic_power_off();
    /* Reached only when the PMIC refused: a successful software power-off
     * drops DCDC1 and the ESP dies before this statement executes. */
    ESP_LOGE(TAG, "bsp_pmic_power_off() returned %s - still powered",
             esp_err_to_name(power_off));
    return power_off == ESP_OK ? ESP_ERR_INVALID_STATE : power_off;
}

